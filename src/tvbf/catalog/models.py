class Show(Base):
    __tablename__ = "show"
    __table_args__ = (
        UniqueConstraint("tmdb_id", name="uq_show_tmdb_id"),
        # The migration's mapping tiers look shows up by these two and nothing
        # else (project spec: `/find` by tvdb_id, then imdb_id). Every other
        # external id is stored but never searched.
        Index("ix_show_tvdb_id", "tvdb_id"),
        Index("ix_show_imdb_id", "imdb_id"),
        CheckConstraint(
            "match_method IS NULL OR match_method IN ('tvdb_id', 'imdb_id', 'title_year')",
            name="ck_show_match_method",
        ),
        {"schema": SCHEMA},
    )

    id: Mapped[int] = mapped_column(BigInteger, _surrogate(_SHOW_ID_START), primary_key=True)
    tmdb_id: Mapped[int | None] = mapped_column(Integer)
    # How the migration arrived at this row's `tmdb_id` (NEU-1043) — one of
    # `tvdb_id` / `imdb_id` / `title_year`, mirroring the three mapping tiers.
    #
    # **The point of it is that two of those tiers are exact and one is not.**
    # A bare `tmdb_id` makes a `/find` hit and a title guess indistinguishable
    # forever; this column is what lets tier 3 be read more sceptically, audited,
    # or retracted as a batch (`WHERE match_method = 'title_year'`) if the
    # go/no-go turns one up wrong.
    #
    # NULL means *this row was not mapped by the migration* — either nothing
    # matched it, or it is a row the TMDB ingest inserted directly, which knows
    # its `tmdb_id` without having had to match anything. It is not a fourth
    # tier, and `tmdb_id IS NULL AND match_method IS NULL` remains the
    # locally-authored row of ADR-0008.
    #
    # Unlike `status`, this vocabulary is ours, so a CHECK constraint is right:
    # a typo'd method is a bug in our own writer rather than an upstream value
    # we do not control.
    match_method: Mapped[str | None] = mapped_column(Text)

    name: Mapped[str] = mapped_column(Text, nullable=False)
    # The untranslated title, in the show's own language. Together with
    # `translation` this *is* the TVBF: Localization project.
    original_name: Mapped[str | None] = mapped_column(Text)
    overview: Mapped[str | None] = mapped_column(Text)
    tagline: Mapped[str | None] = mapped_column(Text)
    homepage: Mapped[str | None] = mapped_column(Text)
    type: Mapped[str | None] = mapped_column(Text)
    adult: Mapped[bool] = mapped_column(
        Boolean, nullable=False, server_default=text("false"), default=False
    )

    # TMDB's string, stored verbatim — `Returning Series` / `Planned` /
    # `In Production` / `Ended` / `Canceled` (audit D1). All five were confirmed
    # against a 1,000-show sweep and no sixth value appeared
    # (`scripts/probe_tmdb_status_vocabulary.py`). Not translated to our old
    # four-value vocabulary: a translation layer would be maintained forever and
    # TMDB's is strictly more informative — `Canceled` is a distinction we cannot
    # currently express at all. No CHECK constraint for the same reason
    # `tvmaze.season` carries no unique key: a vocabulary we do not own is not
    # something to abort an ingest over.
    status: Mapped[str | None] = mapped_column(Text)
    # Generated, not written by ingest — the single piece of status that carries
    # behavior, and the one a straight port gets wrong. Every `status == "Ended"`
    # comparison routes through here instead; without it, canceled shows read as
    # still-running, breaking "finished" for exactly the shows most likely to be
    # finished. Computed in the database so it cannot drift from `status`.
    is_ended: Mapped[bool] = mapped_column(
        Boolean,
        Computed("coalesce(status IN ('Ended', 'Canceled'), false)", persisted=True),
        nullable=False,
    )
    # A genuinely separate boolean per the audit. Measured caveat: across the
    # same 1,000-show sweep it was perfectly determined by `status` (true for
    # Returning Series / In Production / Planned, false for Ended / Canceled), so
    # it carried no information `status` did not. Stored anyway — it rides the
    # same request, and the audit's claim was made about TMDB's model rather than
    # about one sample.
    in_production: Mapped[bool | None] = mapped_column(Boolean)

    first_air_date: Mapped[date | None] = mapped_column(Date)
    last_air_date: Mapped[date | None] = mapped_column(Date)

    # The browse `language` filter reads this (audit D3): it is the only one of
    # TMDB's three language concepts with exactly one value per show, which the
    # filter's exact-match semantics require. Note the values change shape — TV
    # Maze stored "English", TMDB stores "en". Not an FK to `language`: that
    # table is populated from `spoken_languages[]`, which need not contain a
    # show's original language, and an FK would make ingest order load-bearing
    # for no gain.
    original_language: Mapped[str | None] = mapped_column(Text)

    popularity: Mapped[float | None] = mapped_column(Double)
    vote_average: Mapped[Decimal | None] = mapped_column(Numeric(5, 3))
    # New at show grain: lets us weight a rating rather than trust a 10.0 from
    # three voters.
    vote_count: Mapped[int | None] = mapped_column(Integer)

    poster_path: Mapped[str | None] = mapped_column(Text)
    backdrop_path: Mapped[str | None] = mapped_column(Text)

    # Both **exclude season 0** — measured, and the same convention D2 adopts for
    # our own completion math.
    number_of_episodes: Mapped[int | None] = mapped_column(Integer)
    number_of_seasons: Mapped[int | None] = mapped_column(Integer)

    # TMDB's own series-level runtime array, stored verbatim, and usually empty:
    # 6 of 7 sampled shows returned `[]` (audit D4).
    episode_run_time: Mapped[list[int] | None] = mapped_column(ARRAY(Integer))
    # The scalar the SPA renders, derived at ingest as the **median of the show's
    # episode runtimes** — populated for 94.9% of episodes, against TMDB's
    # series-level field which is mostly absent. Median rather than mean so a
    # feature-length finale does not drag a 22-minute sitcom upward.
    #
    # **Ordering constraint, not a detail:** this cannot be finalised until every
    # season's episodes are in hand, including `get_tv_season` overflow, and must
    # be recomputed whenever the daily delta adds episodes.
    runtime: Mapped[int | None] = mapped_column(Integer)

    # Denormalised pointers, refreshed by the daily delta. Derivable from the
    # episode rows — but a derivable field still costs a full ~1.5-hour re-ingest
    # to add later, while a nullable FK costs nothing now, and TMDB's answer is
    # authoritative where ours is inference. Treat them as a cache: read a live
    # query where one is available.
    #
    # `use_alter` because show and episode reference each other. Postgres is
    # happy with the cycle; SQLAlchemy's table sort is not, and would refuse to
    # emit `create_all` without it.
    last_episode_to_air_id: Mapped[int | None] = mapped_column(
        ForeignKey(
            f"{SCHEMA}.episode.id",
            ondelete="SET NULL",
            use_alter=True,
            name="fk_show_last_episode_to_air",
        )
    )
    next_episode_to_air_id: Mapped[int | None] = mapped_column(
        ForeignKey(
            f"{SCHEMA}.episode.id",
            ondelete="SET NULL",
            use_alter=True,
            name="fk_show_next_episode_to_air",
        )
    )

    # `external_ids`, flattened onto the row rather than given a 1:1 table — the
    # shape `tvmaze.show.externals_*` already had, and the mapping tiers want
    # `tvdb_id` and `imdb_id` without a join. Measured set, 2026-08-09.
    imdb_id: Mapped[str | None] = mapped_column(Text)
    tvdb_id: Mapped[int | None] = mapped_column(Integer)
    tvrage_id: Mapped[int | None] = mapped_column(Integer)
    wikidata_id: Mapped[str | None] = mapped_column(Text)
    freebase_id: Mapped[str | None] = mapped_column(Text)
    freebase_mid: Mapped[str | None] = mapped_column(Text)
    facebook_id: Mapped[str | None] = mapped_column(Text)
    instagram_id: Mapped[str | None] = mapped_column(Text)
    twitter_id: Mapped[str | None] = mapped_column(Text)

    ingested_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    # When a **complete** TMDB payload was last mirrored onto this row — the
    # full catalog ingest's resumability watermark (NEU-1034), and the same
    # device `tvmaze.show.akas_synced_at` already is.
    #
    # It exists because "already ingested" and "row already present" are
    # different questions here, where under TV Maze they were the same one. The
    # migration copies ~89k shows into this table (NEU-1042) and maps a
    # `tmdb_id` onto most of them (NEU-1043), so those rows exist and are
    # correctly identified while still holding TV Maze data. An ingest resuming
    # on row-existence would skip exactly the shows users track.
    #
    # NULL therefore means *no full TMDB pass has covered this row yet* — true
    # of a copied row, and true of a locally-authored one forever.
    tmdb_synced_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    # Set when the show stops appearing in the daily id export, i.e. TMDB has
    # deleted it. The row is never removed: `app.user_show_watch` and
    # `app.user_show_rating` cascade from here, so a delete would destroy user
    # data nothing upstream could restore (ADR-0005). Locally-authored rows are
    # exempt by definition — they were never in the feed.
    deleted_upstream_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class Season(Base):
    __tablename__ = "season"
    __table_args__ = (
        UniqueConstraint("tmdb_id", name="uq_season_tmdb_id"),
        Index("ix_season_show_id_number", "show_id", "season_number"),
        {"schema": SCHEMA},
    )
    # **No UNIQUE (show_id, season_number)**, and that is a decision rather than a
    # port. TV Maze reuses a season number within one show on long-running
    # programs that catalogue by calendar year, and a unique key aborts ingestion
    # on exactly those. TMDB was checked for the same quirk and did not show it —
    # 0 of 754 resolved shows had a duplicate `season_number`
    # (`scripts/probe_tmdb_status_vocabulary.py`) — but 754 is a rounding error
    # against TMDB's ~228k TV series, the constraint buys nothing (upserts
    # conflict-target `tmdb_id`, not this pair), and the downside is an integrity
    # error that kills a multi-hour pass on a long-tail show. A plain index
    # carries the lookups instead.

    id: Mapped[int] = mapped_column(BigInteger, _surrogate(_SEASON_ID_START), primary_key=True)
    tmdb_id: Mapped[int | None] = mapped_column(Integer)
    show_id: Mapped[int] = mapped_column(
        ForeignKey(f"{SCHEMA}.show.id", ondelete="CASCADE"), nullable=False
    )
    # 0 for specials (audit D2). Not nullable: TMDB always numbers a season.
    season_number: Mapped[int] = mapped_column(Integer, nullable=False)
    name: Mapped[str | None] = mapped_column(Text)
    overview: Mapped[str | None] = mapped_column(Text)
    poster_path: Mapped[str | None] = mapped_column(Text)
    air_date: Mapped[date | None] = mapped_column(Date)
    vote_average: Mapped[Decimal | None] = mapped_column(Numeric(5, 3))
    # From `seasons[]` on the series payload, not from the season payload itself.
    episode_count: Mapped[int | None] = mapped_column(Integer)


class Episode(Base):
    __tablename__ = "episode"
    __table_args__ = (
        UniqueConstraint("tmdb_id", name="uq_episode_tmdb_id"),
        Index("ix_episode_show_id_season_number", "show_id", "season_number"),
        Index("ix_episode_season_id", "season_id"),
        {"schema": SCHEMA},
    )

    id: Mapped[int] = mapped_column(BigInteger, _surrogate(_EPISODE_ID_START), primary_key=True)
    tmdb_id: Mapped[int | None] = mapped_column(Integer)
    show_id: Mapped[int] = mapped_column(
        ForeignKey(f"{SCHEMA}.show.id", ondelete="CASCADE"), nullable=False
    )
    # SET NULL rather than CASCADE, matching `tvmaze.episode`: a season pruned
    # because the payload stopped naming it (ADR-0004) must not take user watch
    # history with it.
    season_id: Mapped[int | None] = mapped_column(
        ForeignKey(f"{SCHEMA}.season.id", ondelete="SET NULL")
    )
    # Denormalised from the season so aired-count and ordering queries need no
    # join — and so the season-0 predicate D2 requires is one column away.
    season_number: Mapped[int] = mapped_column(Integer, nullable=False)
    # Not nullable, unlike `tvmaze.episode.number`. A null number was TV Maze's
    # marker for a special; under TMDB a special is season 0 with a real episode
    # number (audit D2).
    episode_number: Mapped[int] = mapped_column(Integer, nullable=False)
    name: Mapped[str | None] = mapped_column(Text)
    overview: Mapped[str | None] = mapped_column(Text)
    # A date and nothing more. TMDB carries no time component, so
    # `tvmaze.episode.airtime` has no counterpart and retires with it (audit §6).
    air_date: Mapped[date | None] = mapped_column(Date)
    runtime: Mapped[int | None] = mapped_column(Integer)
    still_path: Mapped[str | None] = mapped_column(Text)
    production_code: Mapped[str | None] = mapped_column(Text)
    # `premiere` / `mid_season` / `finale` / `standard`, straight from upstream —
    # finale detection with no heuristic, which is what Push Notifications would
    # otherwise have to invent. No CHECK: the vocabulary is TMDB's, not ours.
    episode_type: Mapped[str | None] = mapped_column(Text)
    vote_average: Mapped[Decimal | None] = mapped_column(Numeric(5, 3))
    vote_count: Mapped[int | None] = mapped_column(Integer)
    # The whole of the `screened_theatrically` namespace, which returns nothing
    # but a list of episodes. A flag is the faithful shape; a table would be a
    # join to store one bit.
    screened_theatrically: Mapped[bool] = mapped_column(
        Boolean, nullable=False, server_default=text("false"), default=False
    )


