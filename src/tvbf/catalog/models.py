from tvbf.db import Base

SCHEMA = "catalog"

# Where the generated identities start.
#
# The migration preserves TV Maze's ids as `catalog.*.id` so `app`'s existing
# rows keep pointing at the right catalog row without being rewritten. Prod's
# maxima are show 93,469 / season 204,038 / episode 3,694,622; starting the
# sequences well clear of those means a generated id can never collide with a
# preserved one, and the gap leaves room for the mirror to have grown between
# now and cutover.
_SHOW_ID_START = 1_000_000
_SEASON_ID_START = 1_000_000
_EPISODE_ID_START = 10_000_000


def _surrogate(start: int = 1) -> Identity:
    """`GENERATED BY DEFAULT AS IDENTITY`, optionally starting past the migrated ids.

    `always=False` is the load-bearing half: the migration supplies explicit ids
    and `GENERATED ALWAYS` would refuse them outright.
    """
    return Identity(always=False, start=start)


