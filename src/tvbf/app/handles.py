"""The reserved-handle blocklist (NEU-1163 §3).

A handle is claimed once and can never be taken back from whoever holds it,
while a word can be un-reserved later by deleting a line. That asymmetry is the
whole argument for a long defensive list: reserving costs nothing now, and it
keeps a future public-profile URL (`/{handle}`) open as an option even though
nothing in the SPA routes on a handle today.

**Source.** The bulk of the list is vendored from The Big Username Blocklist,
<https://github.com/marteinn/The-Big-Username-Blocklist> (MIT, Copyright (c)
2015-2021 Martin Sandstrom), `list.txt` retrieved 2026-08-21: 541 entries,
filtered to the 443 matching `^[a-z][a-z0-9_]{2,29}$`. Anything outside
that charset can never be claimed anyway, so carrying it would be noise -- `me`
is dropped by the length floor for the same reason, not by oversight.

Two groups are added on top of it: this product's own names and the operational
words the vendored list happens to lack, and a **snapshot of the SPA's top-level
routes as of this revision**. The route group does not track anything -- the
backend cannot import `tvbf-frontend/src/router.tsx` -- so a route added later
is not automatically reserved. That is a known and accepted hole rather than a
bug. The SPA spells those paths with hyphens (`/my-shows`, `/verify-email`);
the underscore forms below are what is actually claimable as a handle, which is
why they are the forms reserved.

**466 entries in total.** The count is whatever the filter and the two
additions yield; it is not a number anything asserts against by hand.

`migrations/versions/<rev>_add_user_handle.py` restates these same strings as a
SQL array literal. That duplication is deliberate and is explained there.
"""

